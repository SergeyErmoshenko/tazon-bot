"""Форматирование чисел для сообщений и графиков.

Разделитель разрядов — неразрывный пробел (U+00A0): в Telegram число
не разорвётся переносом строки. Задаётся escape-последовательностью,
чтобы в исходнике не завёлся визуально неотличимый символ.
"""
from __future__ import annotations

NBSP = "\u00a0"  # неразрывный пробел, задан явно


def fmt_rub(n: int | None) -> str:
    """1490 -> '1 490' (с неразрывными пробелами)."""
    if n is None:
        return "—"
    return f"{n:,}".replace(",", NBSP)
